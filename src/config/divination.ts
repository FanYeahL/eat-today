/**
 * 饭签 · 签文与吉位
 * ─────────────────────────────────────────────
 * 水占抽到一道菜后，签纸上除了菜名/emoji，还显影一句「签文」和一个「吉位」。
 *
 * 设计取向（与全站「温柔朋友语气」一致）：
 * - 签文 verse：通用治愈系短句，不绑定具体菜，随机抽一条。像朋友帮你拿主意时
 *   随口的一句暖话，留点占卜仪式感，但不故弄玄虚。
 * - 吉位 grade：按这道菜的属性轻判定（辣度/清淡/高热量/推荐度），给个有食物画面感的
 *   吉位词。纯趣味，不影响任何抽取概率——只是让签纸更有「签」的样子。
 */

import type { Food } from "@/types/food";

/**
 * 通用签文池（随机抽一条）。
 * 朋友语气、治愈、不绑定菜——给签纸一点温度和仪式感。
 */
export const VERSES: string[] = [
  "今天的胃，想要一口热乎的。宜近不宜远。",
  "别纠结啦，缘分把它推到你面前了。",
  "顺着这一口吃下去，今天会顺的。",
  "想吃的时候就去吃，这是今天最不会后悔的决定。",
  "这一签，是来提醒你好好吃饭的。",
  "馋了就是身体在说话，听它的。",
  "近处就有好味道，不用跑远。",
  "今天的好运气，藏在这一餐里。",
  "拿不定主意的时候，让胃替你选。",
  "就它了——别再刷手机找第二家。",
  "热乎乎吃完，烦心事会轻一点。",
  "今天值得对自己好一点，从这顿开始。",
  "一个人吃也要好好吃，这签替你点头。",
  "犒劳一下最近辛苦的你，吃这个。",
  "简单一餐，也能把日子过得有滋味。",
  "想好了就去，好吃的不等人。",
  "这口下去，半天的疲惫都化开了。",
  "今天的答案很清楚：先把饭吃了。",
  "胃舒服了，心情自然就晴了。",
  "别想太多，香就完事了。",
];

/** 从签文池随机抽一条 */
export function verseFor(): string {
  return VERSES[Math.floor(Math.random() * VERSES.length)];
}

/**
 * 按菜的属性轻判定吉位。
 * 纯趣味展示，不参与抽取概率。判定优先级从上到下，命中即返回：
 * - 够辣（spicy>=2）→ 热烈系
 * - 健康轻食 / 清淡 → 清和系
 * - 高热量且非轻食 → 治愈系（大口吃的满足）
 * - 强推（recommend>=5）→ 上上签
 * - 其余 → 平和的中吉
 * 同一道菜结果稳定（不随机），让「这道菜=这个吉位」有确定感。
 */
export function gradeFor(food: Food): string {
  if (food.spicy >= 2) return "热烈 · 大吉";
  if (food.tags.includes("健康轻食") || food.tags.includes("清淡"))
    return "清和 · 中吉";
  if (food.tags.includes("高热量") && !food.tags.includes("健康轻食"))
    return "治愈 · 大吉";
  if (food.recommend >= 5) return "上上签";
  return "安稳 · 中吉";
}
